// Generates tokens-v3.css (Tailwind v3 / shadcn-HSL edition) from tokens.css, the
// canonical file. Run after every edit to tokens.css: node scripts/build-v3.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const src = readFileSync(`${root}tokens.css`, 'utf8');

// Body of the first `<selector> {` block at the start of a line.
const block = (selector) => {
  const start = src.search(new RegExp(`^${selector.replace('.', '\\.')} \\{`, 'm'));
  if (start < 0) throw new Error(`no ${selector} block in tokens.css`);
  return src.slice(src.indexOf('{', start) + 1, src.indexOf('}', start));
};

const vars = (body) => [...body.matchAll(/^\s*(--[\w-]+):\s*([^;]+);/gm)].map(([, name, value]) => [name, value.trim()]);

const round = (n) => String(Math.round(n * 10) / 10);
const hsl = (hex) => {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
  if (max === min) return `0 0% ${round(l * 100)}%`;
  const d = max - min, s = d / (1 - Math.abs(2 * l - 1));
  const h = max === r ? ((g - b) / d) % 6 : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return `${Math.round(((h * 60) + 360) % 360)} ${Math.round(s * 100)}% ${round(l * 100)}%`;
};

// shadcn v3 calls the sidebar surface --sidebar-background.
const rename = (name) => (name === '--sidebar' ? '--sidebar-background' : name);

const line = ([name, value]) => {
  if (/^#[0-9a-f]{6}$/i.test(value)) return `  ${rename(name)}: ${hsl(value)}; /* ${value} */`;
  const alias = value.match(/^var\((--[\w-]+)\)$/);
  if (alias) return `  ${name}: hsl(var(${rename(alias[1])}));`;
  return `  ${name}: ${value};`;
};

// .dark also carries Studio's --color-* (Tailwind v4 @theme) overrides; v3 apps don't use them.
const shadcn = ([name]) => !name.startsWith('--color-');

const out = `/* GENERATED by scripts/build-v3.mjs from tokens.css. Do not edit by hand.
 * Conceptual Works tokens, Tailwind v3 / shadcn-HSL edition, as HSL triplets for apps
 * whose tailwind.config maps colours as hsl(var(--x)). Scoped: applies only under
 * <html class="cw-style">, so an app can opt one surface in (e.g. the OSIRIS admin)
 * without touching the rest. html.* selectors outrank :root / .dark. */

html.cw-style {
${vars(block(':root')).filter(shadcn).map(line).join('\n')}
}

html.cw-style.dark {
${vars(block('.dark')).filter(shadcn).map(line).join('\n')}
}

html.cw-style body {
  font-family: 'Helvetica Neue', Arial, sans-serif;
}
`;

writeFileSync(`${root}tokens-v3.css`, out);
console.log('tokens-v3.css written');
